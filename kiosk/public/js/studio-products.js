export const STUDIO_PRODUCT_PROFILES = Object.freeze(Object.fromEntries(
    PROFILE_LIST.map((profile) => [profile.type, Object.freeze({
        ...profile,
        controlSections: Object.freeze(profile.controlSections.map((section) => Object.freeze({ ...section }))),
    })])
));

export const STUDIO_PRODUCT_TYPES = Object.freeze(PROFILE_LIST.map((profile) => profile.type));

export const STUDIO_PRODUCT_SECTION_IDS = Object.freeze([
    ...new Set(PROFILE_LIST.flatMap((profile) => profile.controlSections.map((section) => section.id))),
]);

export function getStudioProductProfile(productType) {
    return STUDIO_PRODUCT_PROFILES[productType] || STUDIO_PRODUCT_PROFILES.keychain;
}
